import React, { useEffect, useMemo, useRef, useState } from "react";
import { save } from "@tauri-apps/plugin-dialog";
import { Check, Copy, FileDown, Search, X } from "lucide-react";
import { useTranslation } from "react-i18next";
import { toast } from "sonner";
import { commands, type HistoryEntry } from "@/bindings";
import { formatDateTime } from "@/utils/dateFormat";
import { Button } from "../../ui/Button";
import { Dialog } from "../../ui/Dialog";
import { Input } from "../../ui/Input";
import { copyToClipboard } from "./clipboard";
import { MeetingBadge } from "./MeetingBadge";
import { MeetingNoteSection } from "./MeetingNoteSection";
import {
  EXPORT_EXTENSIONS,
  baseName,
  buildSrt,
  buildTranscriptMarkdown,
  buildVtt,
  formatSegmentTimestamp,
  suggestedExportFileName,
  transcriptText,
  type SpeakerNames,
  type TranscriptExportFormat,
} from "./transcriptExport";

/** The colors the transcript's speaker chips cycle through, one per speaker
 * number: S1 teal, S2 violet, S3 pink, S4 orange — the sortformer stops at
 * four. Fixed by number, so the same voice keeps its color everywhere. */
const SPEAKER_COLORS = ["#0d9488", "#7c3aed", "#db2777", "#ea580c"];

const speakerColor = (id: number): string =>
  SPEAKER_COLORS[(id - 1) % SPEAKER_COLORS.length];

/** The names a diarized meeting keeps until they are saved, indexed by
 * speaker number (S1 is index 0); gaps stay `null` so a later speaker can be
 * named without naming the ones before it. */
const withName = (
  names: (string | null)[],
  id: number,
  value: string,
): (string | null)[] => {
  const next = names.slice();
  next[id - 1] = value;
  return next;
};

interface TranscriptDialogProps {
  entry: HistoryEntry;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

/** The formats the export picker offers, in picker order. SRT and VTT are
 * subtitle files built from the timed segments, so they only make sense for
 * entries that have segments; Markdown is the reading export. */
const EXPORT_FORMATS: {
  id: TranscriptExportFormat;
  labelKey: string;
  /** The save dialog's filter name for this format. */
  fileFilterKey: string;
  /** Subtitle exports cannot exist without timed segments. */
  needsSegments: boolean;
}[] = [
  {
    id: "markdown",
    labelKey: "settings.history.formatMarkdown",
    fileFilterKey: "settings.history.markdownFile",
    needsSegments: false,
  },
  {
    id: "srt",
    labelKey: "settings.history.formatSrt",
    fileFilterKey: "settings.history.srtFile",
    needsSegments: true,
  },
  {
    id: "vtt",
    labelKey: "settings.history.formatVtt",
    fileFilterKey: "settings.history.vttFile",
    needsSegments: true,
  },
];

/** The transcript window: every timed segment of one history entry with its
 * `mm:ss` timestamp, a search box over the text, a copy button for the whole
 * transcript and an export the user saves to a file they pick — as Markdown
 * to read, or as SRT/VTT subtitles for video players. A meeting's draft
 * note, generated by the local LLM on a click, sits above the transcript. */
export const TranscriptDialog: React.FC<TranscriptDialogProps> = ({
  entry,
  open,
  onOpenChange,
}) => {
  const { t, i18n } = useTranslation();
  const [query, setQuery] = useState("");
  const [copied, setCopied] = useState(false);
  const [exporting, setExporting] = useState(false);
  const [format, setFormat] = useState<TranscriptExportFormat>("markdown");
  const searchRef = useRef<HTMLInputElement>(null);
  const transcriptRef = useRef<HTMLOListElement>(null);
  // A quote clicked in the note's "Ask" tab: the segment to jump to, cleared
  // once the jump has been made. The search is dropped first, so a hidden
  // segment can still be jumped to.
  const [pendingJump, setPendingJump] = useState<number | null>(null);
  const [highlightT0, setHighlightT0] = useState<number | null>(null);
  const highlightTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  // S-29: the names this window edits, kept locally until a blur saves them
  // on the entry; the diarization's own "find speakers" pass runs while its
  // button is pressed, model download included.
  const [names, setNames] = useState<(string | null)[]>([]);
  const [findingSpeakers, setFindingSpeakers] = useState(false);

  const segments = useMemo(
    () => entry.metadata?.segments ?? [],
    [entry.metadata?.segments],
  );
  const durationSeconds = entry.metadata?.duration_secs ?? null;
  const isMeeting = entry.source === "meeting";
  const formattedDate = formatDateTime(String(entry.timestamp), i18n.language);
  const hasSegments = segments.length > 0;
  // The speakers the diarization found: the sorted set of speaker numbers
  // on the segments. Empty when the meeting was never diarized — no model on
  // the machine — and the transcript then reads exactly as it did.
  const speakerIds = useMemo(
    () =>
      Array.from(
        new Set(
          segments
            .map((segment) => segment.speaker_id)
            .filter((id): id is number => id != null),
        ),
      ).sort((a, b) => a - b),
    [segments],
  );
  const hasSpeakers = speakerIds.length > 0;
  const speakerCount = hasSpeakers ? speakerIds[speakerIds.length - 1] : 0;
  const storedNames: SpeakerNames = entry.metadata?.speaker_names;

  // Re-read the stored names whenever the entry brings new ones back (a
  // save, or another window naming the same meeting).
  useEffect(() => {
    setNames((storedNames ?? []).slice());
  }, [storedNames]);

  /** The label one segment's speaker shows: the name the user gave, or the
   * speaker's own number ("S2"). */
  const speakerLabel = (id: number): string =>
    names[id - 1]?.trim() || `S${id}`;

  const saveNames = async () => {
    if (!speakerCount) return;
    const payload = Array.from({ length: speakerCount }, (_, index) =>
      names[index] ? names[index] : null,
    );
    const result = await commands.setMeetingSpeakerNames(entry.id, payload);
    if (result.status !== "ok") {
      toast.error(t("settings.history.speakersSaveFailed"));
    }
  };

  /** Find the meeting's speakers now: run the diarization model over its
   * recording (downloading the model first when this machine lacks it) and
   * merge the speakers into the stored segments. The updated entry arrives
   * through the history update the command announces; the transcript was
   * never blocked while it ran. */
  const findSpeakers = async () => {
    if (findingSpeakers) return;
    setFindingSpeakers(true);
    try {
      if (!(await commands.isDiarizationModelDownloaded())) {
        const download = await commands.downloadDiarizationModel();
        if (download.status !== "ok") {
          toast.error(t("settings.history.speakersDownloadFailed"));
          return;
        }
      }
      const result = await commands.diarizeMeetingEntry(entry.id);
      if (result.status !== "ok") {
        toast.error(result.error);
      }
    } catch (error) {
      console.error("Failed to find the meeting's speakers:", error);
      toast.error(t("settings.history.speakersFindFailed"));
    } finally {
      setFindingSpeakers(false);
    }
  };
  const selectedFormat =
    EXPORT_FORMATS.find((option) => option.id === format) ?? EXPORT_FORMATS[0];

  // A fresh search, a rested copy button and the default format each time
  // the window opens.
  useEffect(() => {
    if (open) {
      setQuery("");
      setCopied(false);
      setFormat("markdown");
      setPendingJump(null);
      setHighlightT0(null);
    } else if (highlightTimer.current) {
      clearTimeout(highlightTimer.current);
      highlightTimer.current = null;
    }
  }, [open]);

  // Bring one segment into view and let it glow for a moment: the "Ask"
  // tab's quotes land here. The search is cleared first so the segment is
  // rendered even when the current filter hid it; the effect below runs
  // once that has happened.
  const jumpToSegment = (t0Ms: number) => {
    setQuery("");
    setPendingJump(t0Ms);
  };

  const needle = query.trim().toLowerCase();

  // Make the pending jump once the cleared search has re-rendered the
  // transcript, so a segment the old filter hid can still be jumped to.
  useEffect(() => {
    if (pendingJump === null) return;
    const row = transcriptRef.current?.querySelector<HTMLElement>(
      `[data-t0="${pendingJump}"]`,
    );
    setPendingJump(null);
    if (!row) return;
    row.scrollIntoView({ behavior: "smooth", block: "center" });
    setHighlightT0(pendingJump);
    if (highlightTimer.current) clearTimeout(highlightTimer.current);
    highlightTimer.current = setTimeout(() => setHighlightT0(null), 2400);
  }, [pendingJump, needle]);
  const visibleSegments = useMemo(
    () =>
      needle
        ? segments.filter((segment) =>
            segment.text.toLowerCase().includes(needle),
          )
        : segments,
    [segments, needle],
  );

  const handleCopy = async () => {
    const copiedOk = await copyToClipboard(
      transcriptText(segments, storedNames),
    );
    if (!copiedOk) {
      toast.error(t("settings.history.copyError"));
      return;
    }
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleExport = async () => {
    setExporting(true);
    try {
      // The user picks the destination; nothing is uploaded anywhere.
      const path = await save({
        defaultPath: suggestedExportFileName(entry, format),
        filters: [
          {
            name: t(selectedFormat.fileFilterKey),
            extensions: [EXPORT_EXTENSIONS[format]],
          },
        ],
      });
      if (!path) return;

      // Subtitle formats come straight from the timed segments; Markdown
      // keeps its header with the title and date.
      const contents =
        format === "srt"
          ? buildSrt(segments, storedNames)
          : format === "vtt"
            ? buildVtt(segments, storedNames)
            : buildTranscriptMarkdown(
                segments,
                {
                  title: entry.title || formattedDate,
                  date: formattedDate,
                  dateLabel: t("settings.history.date"),
                  durationLabel: t("settings.history.duration"),
                  durationSeconds,
                },
                storedNames,
              );

      const result = await commands.exportTextFile(path, contents);
      if (result.status === "ok") {
        toast.success(
          t("settings.history.exportSaved", { name: baseName(path) }),
        );
      } else {
        toast.error(t("settings.history.exportFailed"));
      }
    } catch (error) {
      console.error("Failed to export the transcript:", error);
      toast.error(t("settings.history.exportFailed"));
    } finally {
      setExporting(false);
    }
  };

  return (
    <Dialog
      open={open}
      onOpenChange={onOpenChange}
      title={t("settings.history.transcript")}
      description={
        <span className="flex flex-wrap items-center gap-x-3 gap-y-1">
          <span>{formattedDate}</span>
          {isMeeting && <MeetingBadge />}
          {durationSeconds !== null && (
            <span className="tabular-nums">
              {t("settings.history.duration")}{" "}
              {formatSegmentTimestamp(durationSeconds * 1000)}
            </span>
          )}
        </span>
      }
      closeLabel={t("common.close")}
      className="max-w-2xl!"
      initialFocusRef={searchRef}
      footer={
        <>
          <Button
            variant="secondary"
            size="sm"
            onClick={handleCopy}
            disabled={segments.length === 0}
            className="flex items-center gap-2"
          >
            {copied ? (
              <Check className="h-4 w-4" aria-hidden="true" />
            ) : (
              <Copy className="h-4 w-4" aria-hidden="true" />
            )}
            {t("settings.history.copyTranscript")}
          </Button>
          <div
            role="group"
            aria-label={t("settings.history.exportFormatLabel")}
            className="flex items-center gap-0.5 self-center rounded-lg border border-line-strong bg-wash p-0.5"
          >
            {EXPORT_FORMATS.map((option) => {
              // Subtitle exports need timed segments; without them the
              // choice stays visible but switched off, with the reason on
              // hover, instead of exporting a broken file.
              const disabled = option.needsSegments && !hasSegments;
              return (
                <button
                  key={option.id}
                  type="button"
                  onClick={() => setFormat(option.id)}
                  disabled={disabled}
                  aria-pressed={format === option.id}
                  title={
                    disabled
                      ? t("settings.history.exportNeedsSegments")
                      : undefined
                  }
                  className={`cursor-pointer rounded-md px-2 py-1 text-xs font-semibold transition-colors ${
                    format === option.id
                      ? "bg-logo-primary/20 text-text"
                      : "text-ink-3 hover:bg-line"
                  } ${disabled ? "cursor-not-allowed opacity-50 hover:bg-transparent" : ""}`}
                >
                  {t(option.labelKey)}
                </button>
              );
            })}
          </div>
          <Button
            variant="primary"
            size="sm"
            onClick={handleExport}
            disabled={exporting || !hasSegments}
            className="flex items-center gap-2"
          >
            <FileDown className="h-4 w-4" aria-hidden="true" />
            {t("settings.history.exportAsFormat", {
              format: t(selectedFormat.labelKey),
            })}
          </Button>
        </>
      }
    >
      {isMeeting && (
        <MeetingNoteSection entry={entry} onJumpToSegment={jumpToSegment} />
      )}

      {isMeeting && (hasSpeakers || hasSegments) && (
        <div className="flex flex-wrap items-center gap-x-3 gap-y-2">
          {hasSpeakers ? (
            <>
              <span className="text-xs font-semibold text-ink-3">
                {t("settings.history.speakers")}
              </span>
              {speakerIds.map((id) => {
                const placeholder = t(
                  "settings.history.speakerNamePlaceholder",
                  {
                    id: `S${id}`,
                  },
                );
                return (
                  <div
                    key={id}
                    className="flex items-center gap-1.5 rounded-lg border border-line px-1.5 py-0.5"
                  >
                    <span
                      aria-hidden="true"
                      className="h-2.5 w-2.5 shrink-0 rounded-full"
                      style={{ backgroundColor: speakerColor(id) }}
                    />
                    <Input
                      variant="compact"
                      value={names[id - 1] ?? ""}
                      onChange={(event) =>
                        setNames(withName(names, id, event.target.value))
                      }
                      onBlur={saveNames}
                      placeholder={placeholder}
                      aria-label={placeholder}
                      className="w-32 border-0 bg-transparent focus-visible:ring-0"
                    />
                  </div>
                );
              })}
            </>
          ) : (
            <>
              <span className="text-xs text-ink-3">
                {t("settings.history.speakersNone")}
              </span>
              <Button
                variant="secondary"
                size="sm"
                onClick={findSpeakers}
                disabled={findingSpeakers}
                className="h-6 px-2 text-xs"
              >
                {findingSpeakers
                  ? t("settings.history.speakersFinding")
                  : t("settings.history.speakersFind")}
              </Button>
            </>
          )}
        </div>
      )}

      <div className="relative">
        <Search
          className="pointer-events-none absolute top-1/2 left-2.5 h-3.5 w-3.5 -translate-y-1/2 text-ink-3"
          aria-hidden="true"
        />
        <Input
          ref={searchRef}
          variant="compact"
          value={query}
          onChange={(event) => setQuery(event.target.value)}
          placeholder={t("settings.history.transcriptSearchPlaceholder")}
          aria-label={t("settings.history.transcriptSearchPlaceholder")}
          className="w-full ps-8 pe-7"
        />
        {query && (
          <button
            type="button"
            onClick={() => setQuery("")}
            aria-label={t("common.clear")}
            className="absolute top-1/2 right-1.5 -translate-y-1/2 cursor-pointer rounded p-0.5 text-ink-3 transition-colors hover:text-text"
          >
            <X className="h-3.5 w-3.5" aria-hidden="true" />
          </button>
        )}
      </div>

      <div className="mt-3">
        {visibleSegments.length === 0 ? (
          <p className="py-8 text-center text-sm text-ink-3">
            {needle
              ? t("settings.history.transcriptNoMatches", {
                  query: query.trim(),
                })
              : t("settings.history.transcriptEmpty")}
          </p>
        ) : (
          <ol ref={transcriptRef} className="divide-y divide-line">
            {visibleSegments.map((segment, index) => (
              <li
                key={`${segment.t0_ms}-${index}`}
                data-t0={segment.t0_ms}
                className={`flex gap-3 py-2 first:pt-1 last:pb-1 ${
                  highlightT0 === segment.t0_ms
                    ? "-mx-2 rounded-md bg-logo-primary/15 px-2 transition-colors duration-500"
                    : ""
                }`}
              >
                <span className="w-12 shrink-0 pt-0.5 text-xs font-semibold tabular-nums text-ink-3 select-none">
                  {formatSegmentTimestamp(segment.t0_ms)}
                </span>
                {segment.speaker_id != null && (
                  <span
                    className="mt-0.5 h-fit shrink-0 rounded-md px-1.5 py-0.5 text-[10px] font-bold"
                    style={{
                      backgroundColor: `${speakerColor(segment.speaker_id)}22`,
                      color: speakerColor(segment.speaker_id),
                    }}
                  >
                    {speakerLabel(segment.speaker_id)}
                  </span>
                )}
                <p className="min-w-0 text-sm break-words whitespace-pre-wrap text-text select-text">
                  {segment.text}
                </p>
              </li>
            ))}
          </ol>
        )}
      </div>
    </Dialog>
  );
};
