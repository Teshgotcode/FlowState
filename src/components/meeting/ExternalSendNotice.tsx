import React, { useState } from "react";
import { useTranslation } from "react-i18next";
import { Button } from "../ui/Button";
import { Dialog } from "../ui/Dialog";

interface ExternalSendNoticeProps {
  /** The provider's own label, e.g. "OpenAI" - the name the user sees. */
  providerName: string;
  /** The host the meeting text will be sent to, e.g. "api.openai.com". */
  host: string;
  /** OK generates now; `remember` acknowledges the host from now on. */
  onOk: (remember: boolean) => void;
  /** Any other way out (Escape, X, backdrop) must cancel the generation. */
  onCancel: () => void;
}

/** The blocking gate before a meeting note is generated by an off-machine
 * provider: nothing is sent until OK, and closing the dialog any other way
 * cancels the generation. */
export const ExternalSendNotice: React.FC<ExternalSendNoticeProps> = ({
  providerName,
  host,
  onOk,
  onCancel,
}) => {
  const { t } = useTranslation();
  const [remember, setRemember] = useState(false);

  return (
    <Dialog
      open={true}
      onOpenChange={(open) => {
        if (!open) onCancel();
      }}
      title={t("meeting.externalNotice.title")}
      closeLabel={t("common.close")}
      footer={
        <Button onClick={() => onOk(remember)}>
          {t("meeting.externalNotice.ok")}
        </Button>
      }
    >
      <p className="text-sm text-text">
        {t("meeting.externalNotice.body", { provider: providerName, host })}
      </p>
      <label className="mt-3 flex cursor-pointer items-center gap-2 text-sm text-ink-3">
        <input
          type="checkbox"
          checked={remember}
          onChange={(event) => setRemember(event.target.checked)}
        />
        {t("meeting.externalNotice.remember")}
      </label>
    </Dialog>
  );
};
